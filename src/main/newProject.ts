export async function createProject(selectedPath: string): Promise<string> {
  const selectedFile = resolve(projectFilePath(selectedPath))
  const name = projectName(selectedFile)
  const folderName = `${name}.gmx`
  const selectedFolder = dirname(selectedFile)
  const targetFolder = basename(selectedFolder).toLowerCase() === folderName.toLowerCase()
    ? selectedFolder
    : resolve(selectedFolder, folderName)
  const targetProject = resolve(targetFolder, `${name}.project.gmx`)
  if (await exists(targetFolder)) throw new Error(`A project folder named ${folderName} already exists`)

  const tempFolder = await mkdtemp(join(dirname(targetFolder), '.opengms-new-'))
  const stagedFolder = join(tempFolder, folderName)
  try {
    await Promise.all([
      mkdir(join(stagedFolder, 'Configs'), { recursive: true }),
      mkdir(join(stagedFolder, 'rooms'), { recursive: true })
    ])
    await Promise.all([
      writeFile(join(stagedFolder, `${name}.project.gmx`), projectSource(), 'utf8'),
      writeFile(join(stagedFolder, 'Configs', 'Default.config.gmx'), configSource(name), 'utf8'),
      writeFile(join(stagedFolder, 'rooms', 'room0.room.gmx'), roomSource(), 'utf8')
    ])
    await rename(stagedFolder, targetFolder)
  } finally {
    await rm(tempFolder, { recursive: true, force: true }).catch(() => undefined)
  }
  return targetProject
}
