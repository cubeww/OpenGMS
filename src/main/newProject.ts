import { randomInt, randomUUID } from 'node:crypto'
import { mkdir, mkdtemp, rename, rm, stat, writeFile } from 'node:fs/promises'
import { basename, dirname, join, resolve } from 'node:path'

const comment = '<!--This Document is generated by GameMaker, if you edit it by hand then you do so at your own risk!-->'

function projectFilePath(path: string): string {
  if (/\.project\.gmx$/i.test(path)) return path
  if (/\.project$/i.test(path)) return `${path}.gmx`
  if (/\.gmx$/i.test(path)) return `${path.slice(0, -4)}.project.gmx`
  return `${path}.project.gmx`
}

function projectName(value: string): string {
  const name = basename(value).replace(/\.project\.gmx$/i, '').trim()
  if (
    !name ||
    name.length > 100 ||
    /[<>:"/\\|?*\u0000-\u001f]/.test(name) ||
    /[. ]$/.test(name) ||
    /^(con|prn|aux|nul|com[1-9]|lpt[1-9])(?:\.|$)/i.test(name)
  ) {
    throw new Error('Enter a valid project name')
  }
  return name
}

function xml(value: string): string {
  return value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
}

async function exists(path: string): Promise<boolean> {
  try {
    await stat(path)
    return true
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') return false
    throw error
  }
}

